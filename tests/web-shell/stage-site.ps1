[CmdletBinding()]
param(
    # 검증용 사이트를 만들 디렉터리. 저장소·게임 산출물 밖의 새 경로이거나, 이 도구가 만든(marker 있는) 디렉터리여야 한다.
    [Parameter(Mandatory = $true)][string]$Out,
    # 실제 빌드 산출물 디렉터리(taisei.js/taisei.wasm/data/ 포함). -Mock과 함께 쓰지 않는다.
    [string]$Game,
    # 가짜 로더(mock-taisei.js)를 game/taisei.js로 배치한다.
    [switch]$Mock
)

# web/ 셸과 게임 산출물(또는 mock)을 세션 1의 패키징 규칙(docs/web/BUILD.md)과 같은 배치로 모아
# 로컬 HTTP로 검증할 수 있게 한다. 세션 1의 패키징 명령을 대체하지 않으며 셸 검증 전용이다.
#
# 안전 규칙(원본 삭제 방지):
#   1. 모든 입력(-Mock/-Game, 필수 파일)을 먼저 검증한다. 검증 실패 시 Out은 건드리지 않는다.
#   2. Out은 저장소, web/, 이 스크립트 디렉터리, Game과 같거나 조상·자손이면 거부한다.
#   3. Out이 이미 있으면 이 도구가 남긴 marker 파일이 있을 때만 내용을 교체한다. 임의 디렉터리는 지우지 않는다.

$ErrorActionPreference = 'Stop'
$MarkerName = '.taisei-shell-stage'

function Get-NormalizedPath([string]$Path) {
    # 존재하지 않는 경로도 다룰 수 있도록 Resolve-Path 대신 GetFullPath를 쓴다.
    if (-not [System.IO.Path]::IsPathRooted($Path)) {
        $Path = Join-Path (Get-Location).Path $Path
    }
    $full = [System.IO.Path]::GetFullPath($Path)
    return $full.TrimEnd([System.IO.Path]::DirectorySeparatorChar, [System.IO.Path]::AltDirectorySeparatorChar)
}

function Test-PathOverlap([string]$A, [string]$B) {
    # 같은 경로이거나 한쪽이 다른 쪽의 조상이면 true
    $a = $A.ToLowerInvariant(); $b = $B.ToLowerInvariant()
    $sep = [System.IO.Path]::DirectorySeparatorChar
    return ($a -eq $b) -or $a.StartsWith($b + $sep) -or $b.StartsWith($a + $sep)
}

$repoRoot = Get-NormalizedPath (Join-Path $PSScriptRoot '..\..')
$webDir = Join-Path $repoRoot 'web'
$webGameDir = Join-Path $webDir 'game'
$mockLoader = Join-Path $PSScriptRoot 'mock-taisei.js'

# 1. 입력 검증 (Out을 건드리기 전에 끝낸다)
if ($Mock -and $Game) { throw 'Use either -Mock or -Game, not both.' }
if (-not $Mock -and -not $Game) { throw 'Specify -Mock or -Game <build directory>.' }
foreach ($required in @($webDir, $webGameDir, (Join-Path $webDir 'index.html'), (Join-Path $webGameDir 'index.html'), $mockLoader)) {
    if (-not (Test-Path -LiteralPath $required)) { throw "Shell source is missing: $required" }
}

$gamePath = $null
if ($Game) {
    $gamePath = Get-NormalizedPath $Game
    if (-not (Test-Path -LiteralPath $gamePath -PathType Container)) { throw "Game build directory not found: $gamePath" }
    foreach ($required in @('taisei.js', 'taisei.wasm', 'data')) {
        if (-not (Test-Path -LiteralPath (Join-Path $gamePath $required))) {
            throw "Game build is missing $required in $gamePath"
        }
    }
}

# 2. 출력 경로 검증
$outPath = Get-NormalizedPath $Out
$root = [System.IO.Path]::GetPathRoot($outPath).TrimEnd([System.IO.Path]::DirectorySeparatorChar)
if ($outPath -eq $root) { throw "Out must not be a drive root: $outPath" }
if (Test-PathOverlap $outPath $repoRoot) { throw "Out must be outside the repository ($repoRoot): $outPath" }
if ($gamePath -and (Test-PathOverlap $outPath $gamePath)) { throw "Out must not overlap the game build directory ($gamePath): $outPath" }
if (Test-Path -LiteralPath $outPath -PathType Leaf) { throw "Out is a file, not a directory: $outPath" }

$marker = Join-Path $outPath $MarkerName
if (Test-Path -LiteralPath $outPath) {
    if (-not (Test-Path -LiteralPath $marker -PathType Leaf)) {
        throw "Out already exists and was not created by this tool (no $MarkerName): $outPath. Use a new directory."
    }
    # 이 도구가 만든 디렉터리만 내용을 교체한다(디렉터리 자체는 유지해 실행 중인 서버에 영향이 없게 한다).
    Get-ChildItem -LiteralPath $outPath -Force | Remove-Item -Recurse -Force
} else {
    New-Item -ItemType Directory -Path $outPath | Out-Null
}
Set-Content -LiteralPath $marker -Value "generated by tests/web-shell/stage-site.ps1 $(Get-Date -Format o)" -Encoding ascii

# 3. 배치: web/game/ 제외 파일은 루트로, web/game/*는 game/으로 (세션 1 패키징 규칙과 동일)
$gameOut = Join-Path $outPath 'game'
New-Item -ItemType Directory -Path $gameOut | Out-Null
Get-ChildItem -LiteralPath $webDir -Force |
    Where-Object { $_.Name -ne 'game' } |
    ForEach-Object { Copy-Item -LiteralPath $_.FullName -Destination $outPath -Recurse -Force }
Copy-Item -Path (Join-Path $webGameDir '*') -Destination $gameOut -Recurse -Force

if ($Mock) {
    Copy-Item -LiteralPath $mockLoader -Destination (Join-Path $gameOut 'taisei.js')
    Set-Content -LiteralPath (Join-Path $gameOut 'COPYING.txt') -Value 'mock license placeholder' -Encoding utf8
    Write-Host "Staged mock site at $outPath"
} else {
    foreach ($name in @('taisei.js', 'taisei.wasm', 'background.webp', 'scythe.webp', 'favicon.ico', 'COPYING.txt', 'README.txt')) {
        $src = Join-Path $gamePath $name
        if (Test-Path -LiteralPath $src) { Copy-Item -LiteralPath $src -Destination $gameOut }
    }
    Copy-Item -LiteralPath (Join-Path $gamePath 'data') -Destination (Join-Path $gameOut 'data') -Recurse
    Write-Host "Staged real game site at $outPath (from $gamePath)"
}

Get-ChildItem -LiteralPath $gameOut -File | Select-Object Name, Length
Write-Host "Serve with: python -m http.server 8090 --bind 127.0.0.1 --directory `"$outPath`"  (open /index.html)"
